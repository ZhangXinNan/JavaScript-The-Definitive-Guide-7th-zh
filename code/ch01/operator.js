
// 算术操作符：加减乘除
console.log(2 + 3);
console.log(3 - 2);
console.log(4 * 5);
console.log(3 / 2);

// 算术操作符：简写运算符
let count = 0;
console.log(count++);
console.log(count--);
console.log(count += 2);
console.log(count *= 3);


// 关系操作符
let x = 2, y = 3;
console.log(x === y);
// console.log(x == y);
console.log(x !== y);
console.log(x < y);
console.log(x <= y);
console.log("two" === 'three'); // => false
console.log("two" > "three");   // => true

// 逻辑操作符
console.log(true && false);     // => false
console.log(true || false);     // => true
console.log(!true);             // => false

